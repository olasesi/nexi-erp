import type { ReactNode } from "react";
import { useQuery } from "@tanstack/react-query";
import { Activity, AlertTriangle, Info, Sparkles } from "lucide-react";

import {
  getAdvisorReport,
  getHrmSummary,
  getTeamWorkload,
  getTeamWorkloadSummary,
} from "@/lib/api";
import { formatMonth, formatPercent } from "@/lib/format";
import { useCompany } from "@/lib/use-company";
import { SeverityBadge } from "@/components/ui/badge";
import { Card } from "@/components/ui/card";
import { PageHeader } from "@/components/ui/page-header";
import { Stat } from "@/components/ui/stat";
import { ErrorState, LoadingState } from "@/components/ui/states";
import { RadialGauge, TrendChart } from "@/components/charts";
import type { AdvisorReport } from "@/types";

const CATEGORY_COLORS: Record<string, string> = {
  financial: "#3b82f6",
  sales: "#10b981",
  operations: "#f59e0b",
  team: "#8b5cf6",
  projects: "#0ea5e9",
};

const SEVERITY_ICON: Record<string, typeof Info> = {
  critical: AlertTriangle,
  warning: AlertTriangle,
  info: Info,
  positive: Sparkles,
};

export function HealthPage() {
  const { companyId, isLoading, error, refetch } = useCompany();

  const query = useQuery({
    queryKey: ["advisor", "report", companyId],
    queryFn: () => getAdvisorReport(companyId as number),
    enabled: companyId !== null,
  });

  if (isLoading) return <LoadingState label="Resolving your company…" />;
  if (error || companyId === null) {
    return (
      <ErrorState
        error={
          error instanceof Error ? error : new Error("No company is linked to this account yet.")
        }
        onRetry={() => void refetch()}
      />
    );
  }
  if (query.isLoading) return <LoadingState label="Scoring the business…" />;
  if (query.isError) {
    return <ErrorState error={query.error} onRetry={() => void query.refetch()} />;
  }
  if (!query.data) return <LoadingState />;

  return <HealthContent report={query.data} companyId={companyId} />;
}

function HealthContent({ report, companyId }: { report: AdvisorReport; companyId: number }) {
  const categories = Object.entries(report.categories);
  const trend = report.trend.points;

  const deltaTone =
    report.trend.delta === null || report.trend.delta === undefined
      ? "text-muted"
      : report.trend.delta > 0
        ? "text-success"
        : report.trend.delta < 0
          ? "text-danger"
          : "text-muted";

  return (
    <div className="page">
      <PageHeader
        title="Business Health"
        description={`Scored ${report.score_date} · generated by ${report.generated_by}`}
        actions={
          <BadgeLike>
            {report.coverage.scored} of {report.coverage.total} areas scored
          </BadgeLike>
        }
      />

      <div className="grid-fixed grid-fixed--3">
        <Card title="Overall score" description="Weighted across every scored area">
          <div className="stack stack--2 cluster cluster--center">
            <RadialGauge value={report.overall_score ?? 0} caption="/ 100" size={200} />
            {report.trend.delta !== null && report.trend.delta !== undefined && (
              <p className={`tally ${deltaTone}`}>
                {report.trend.delta > 0 ? "▲" : report.trend.delta < 0 ? "▼" : "•"}{" "}
                {formatPercent(Math.abs(report.trend.delta))} vs previous score
              </p>
            )}
          </div>
        </Card>

        <Card
          title="Category scores"
          description="Each pillar of the business"
          className="col-span-2"
        >
          <div className="grid-fixed grid-fixed--2">
            {categories.map(([key, category]) => (
              <div key={key} className="bucket">
                <div className="cluster cluster--between cluster--baseline">
                  <p className="bucket__label">{category.label ?? key}</p>
                  <p className="bucket__value">{category.score === null ? "—" : category.score}</p>
                </div>
                <div className="bucket__bar">
                  <div
                    className="bucket__bar-fill"
                    style={{
                      width: `${Math.max(category.score ?? 0, 0)}%`,
                      backgroundColor: CATEGORY_COLORS[key] ?? "#3b82f6",
                    }}
                  />
                </div>
                <p className="bucket__note">
                  Weight {category.weight ?? "—"}
                  {category.note ? ` · ${category.note}` : ""}
                </p>
              </div>
            ))}
          </div>
        </Card>
      </div>

      {trend.length > 0 && (
        <Card title="Score history" description={`${trend.length} snapshots`}>
          <TrendChart
            data={trend}
            xKey="score_date"
            formatX={(value) => formatMonth(value.slice(0, 7))}
            formatValue={(value) => String(Math.round(value))}
            series={[
              { key: "overall_score", label: "Overall", color: "#3b82f6" },
              { key: "financial_score", label: "Financial", color: "#10b981" },
              { key: "sales_score", label: "Sales", color: "#8b5cf6" },
              { key: "operations_score", label: "Operations", color: "#f59e0b" },
              { key: "team_score", label: "Team", color: "#0ea5e9" },
            ]}
            title="Business health scores over time"
          />
        </Card>
      )}

      <div className="grid-fixed grid-fixed--3">
        <FeedCard
          title="Alerts"
          items={report.alerts.map((item) => ({ ...item, text: item.detail }))}
        />
        <FeedCard title="Insights" items={report.insights} />
        <FeedCard title="Recommendations" items={report.recommendations} />
      </div>

      <TeamWorkloadSection companyId={companyId} />

      <p className="tally">
        <Activity className="icon icon--xs" />
        Recomputed by the scheduled advisor snapshot job.
      </p>
    </div>
  );
}

function FeedCard({
  title,
  items,
}: {
  title: string;
  items: Array<{ key: string; severity: string; domain: string; title: string; text: string }>;
}) {
  return (
    <Card title={title} description={`${items.length} items`}>
      {items.length === 0 ? (
        <p className="state__empty">Nothing here yet.</p>
      ) : (
        <ul className="divided-list">
          {items.map((item, index) => {
            const Icon = SEVERITY_ICON[item.severity] ?? Info;
            return (
              <li key={`${item.key}-${index}`} className="divided-list__item">
                <Icon className="divided-list__icon icon icon--sm" />
                <div className="divided-list__body">
                  <div className="divided-list__head">
                    <p className="divided-list__title">{item.title}</p>
                    <SeverityBadge severity={item.severity} />
                  </div>
                  <p className="divided-list__text">{item.text}</p>
                </div>
              </li>
            );
          })}
        </ul>
      )}
    </Card>
  );
}

function TeamWorkloadSection({ companyId }: { companyId: number }) {
  const hrm = useQuery({
    queryKey: ["hrm", "summary", companyId],
    queryFn: () => getHrmSummary(companyId),
  });
  const workloadSummary = useQuery({
    queryKey: ["team-workload", "summary", companyId],
    queryFn: () => getTeamWorkloadSummary(companyId),
  });
  const workload = useQuery({
    queryKey: ["team-workload", "rows", companyId],
    queryFn: () => getTeamWorkload(companyId),
  });

  const rows = [...(workload.data?.data ?? [])]
    .sort((a, b) => b.total_load - a.total_load)
    .slice(0, 6);

  return (
    <div className="stack stack--4">
      <div className="grid-fixed grid-fixed--2">
        <Card
          title="Headcount"
          description={hrm.data ? `As of ${hrm.data.as_of}` : "People and attendance today"}
        >
          {hrm.isLoading ? (
            <div className="skeleton skeleton--stat" />
          ) : hrm.isError || !hrm.data ? (
            <p className="state__empty">Headcount could not be loaded.</p>
          ) : (
            <div className="stack stack--4">
              <div className="grid-fixed grid-fixed--2">
                <Stat label="Employees" value={hrm.data.total_employees} />
                <Stat label="Working" value={hrm.data.working_employees} />
                <Stat
                  label="Attendance today"
                  value={Math.round(hrm.data.attendance_rate * 100)}
                  unit="%"
                />
                <Stat
                  label="Pending leave"
                  value={hrm.data.pending_leaves}
                  tone={hrm.data.pending_leaves > 0 ? "danger" : "default"}
                />
              </div>
              <p className="tally">
                {hrm.data.attendance_today.present} present · {hrm.data.attendance_today.absent}{" "}
                absent · {hrm.data.attendance_today.leave} on leave · {hrm.data.on_leave_today} away
                today
              </p>
            </div>
          )}
        </Card>

        <Card title="Open work" description="Tasks, tickets and timesheets awaiting action">
          {workloadSummary.isLoading ? (
            <div className="skeleton skeleton--stat" />
          ) : workloadSummary.isError || !workloadSummary.data ? (
            <p className="state__empty">Workload could not be loaded.</p>
          ) : (
            <div className="grid-fixed grid-fixed--2">
              <Stat label="Open tasks" value={workloadSummary.data.total_open_tasks} />
              <Stat label="Open tickets" value={workloadSummary.data.total_open_tickets} />
              <Stat
                label="Pending timesheets"
                value={workloadSummary.data.total_pending_timesheets}
              />
              <Stat label="Average load" value={workloadSummary.data.average_load} />
            </div>
          )}
        </Card>
      </div>

      <Card title="Heaviest workload" description="Top six employees by open items" flush>
        {workload.isLoading ? (
          <div className="skeleton skeleton--table" />
        ) : workload.isError ? (
          <p className="state__empty">Workload could not be loaded.</p>
        ) : rows.length === 0 ? (
          <p className="state__empty">Nobody has open work right now.</p>
        ) : (
          <div className="inline-table__scroll">
            <table className="inline-table">
              <thead>
                <tr className="inline-table__head-row">
                  <th className="inline-table__th">Employee</th>
                  <th className="inline-table__th inline-table__th--num">Tasks</th>
                  <th className="inline-table__th inline-table__th--num">Tickets</th>
                  <th className="inline-table__th inline-table__th--num">Timesheets</th>
                  <th className="inline-table__th inline-table__th--num">Total load</th>
                </tr>
              </thead>
              <tbody>
                {rows.map((row) => (
                  <tr className="inline-table__row" key={row.employee_id}>
                    <td className="inline-table__td inline-table__td--strong">
                      {row.employee_name}
                    </td>
                    <td className="inline-table__td inline-table__td--num">{row.open_tasks}</td>
                    <td className="inline-table__td inline-table__td--num">{row.open_tickets}</td>
                    <td className="inline-table__td inline-table__td--num">
                      {row.pending_timesheets}
                    </td>
                    <td className="inline-table__td inline-table__td--num inline-table__td--strong">
                      {row.total_load}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </div>
  );
}

function BadgeLike({ children }: { children: ReactNode }) {
  return <span className="badge badge--gray">{children}</span>;
}
