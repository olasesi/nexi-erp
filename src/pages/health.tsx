import type { ReactNode } from "react";
import { useQuery } from "@tanstack/react-query";
import { Activity, AlertTriangle, Info, Sparkles } from "lucide-react";

import { getAdvisorReport } from "@/lib/api";
import { formatMonth, formatPercent } from "@/lib/format";
import { useCompany } from "@/lib/use-company";
import { SeverityBadge } from "@/components/ui/badge";
import { Card } from "@/components/ui/card";
import { PageHeader } from "@/components/ui/page-header";
import { ErrorState, LoadingState } from "@/components/ui/states";
import { RadialGauge, TrendChart } from "@/components/charts";
import type { AdvisorReport } from "@/types";

const CATEGORY_COLORS: Record<string, string> = {
  financial: "#3b82f6",
  sales: "#10b981",
  operations: "#f59e0b",
  team: "#8b5cf6",
  projects: "#0ea5e9",
};

const SEVERITY_ICON: Record<string, typeof Info> = {
  critical: AlertTriangle,
  warning: AlertTriangle,
  info: Info,
  positive: Sparkles,
};

export function HealthPage() {
  const { companyId, isLoading, error, refetch } = useCompany();

  const query = useQuery({
    queryKey: ["advisor", "report", companyId],
    queryFn: () => getAdvisorReport(companyId as number),
    enabled: companyId !== null,
  });

  if (isLoading) return <LoadingState label="Resolving your company…" />;
  if (error || companyId === null) {
    return (
      <ErrorState
        error={
          error instanceof Error ? error : new Error("No company is linked to this account yet.")
        }
        onRetry={() => void refetch()}
      />
    );
  }
  if (query.isLoading) return <LoadingState label="Scoring the business…" />;
  if (query.isError) {
    return <ErrorState error={query.error} onRetry={() => void query.refetch()} />;
  }
  if (!query.data) return <LoadingState />;

  return <HealthContent report={query.data} />;
}

function HealthContent({ report }: { report: AdvisorReport }) {
  const categories = Object.entries(report.categories);
  const trend = report.trend.points;

  const deltaTone =
    report.trend.delta === null || report.trend.delta === undefined
      ? "text-muted"
      : report.trend.delta > 0
        ? "text-success"
        : report.trend.delta < 0
          ? "text-danger"
          : "text-muted";

  return (
    <div className="page">
      <PageHeader
        title="Business Health"
        description={`Scored ${report.score_date} · generated by ${report.generated_by}`}
        actions={
          <BadgeLike>
            {report.coverage.scored} of {report.coverage.total} areas scored
          </BadgeLike>
        }
      />

      <div className="grid-fixed grid-fixed--3">
        <Card title="Overall score" description="Weighted across every scored area">
          <div className="stack stack--2 cluster cluster--center">
            <RadialGauge value={report.overall_score ?? 0} caption="/ 100" size={200} />
            {report.trend.delta !== null && report.trend.delta !== undefined && (
              <p className={`tally ${deltaTone}`}>
                {report.trend.delta > 0 ? "▲" : report.trend.delta < 0 ? "▼" : "•"}{" "}
                {formatPercent(Math.abs(report.trend.delta))} vs previous score
              </p>
            )}
          </div>
        </Card>

        <Card
          title="Category scores"
          description="Each pillar of the business"
          className="col-span-2"
        >
          <div className="grid-fixed grid-fixed--2">
            {categories.map(([key, category]) => (
              <div key={key} className="bucket">
                <div className="cluster cluster--between cluster--baseline">
                  <p className="bucket__label">{category.label ?? key}</p>
                  <p className="bucket__value">{category.score === null ? "—" : category.score}</p>
                </div>
                <div className="bucket__bar">
                  <div
                    className="bucket__bar-fill"
                    style={{
                      width: `${Math.max(category.score ?? 0, 0)}%`,
                      backgroundColor: CATEGORY_COLORS[key] ?? "#3b82f6",
                    }}
                  />
                </div>
                <p className="bucket__note">
                  Weight {category.weight ?? "—"}
                  {category.note ? ` · ${category.note}` : ""}
                </p>
              </div>
            ))}
          </div>
        </Card>
      </div>

      {trend.length > 0 && (
        <Card title="Score history" description={`${trend.length} snapshots`}>
          <TrendChart
            data={trend}
            xKey="score_date"
            formatX={(value) => formatMonth(value.slice(0, 7))}
            formatValue={(value) => String(Math.round(value))}
            series={[
              { key: "overall_score", label: "Overall", color: "#3b82f6" },
              { key: "financial_score", label: "Financial", color: "#10b981" },
              { key: "sales_score", label: "Sales", color: "#8b5cf6" },
              { key: "operations_score", label: "Operations", color: "#f59e0b" },
              { key: "team_score", label: "Team", color: "#0ea5e9" },
            ]}
            title="Business health scores over time"
          />
        </Card>
      )}

      <div className="grid-fixed grid-fixed--3">
        <FeedCard
          title="Alerts"
          items={report.alerts.map((item) => ({ ...item, text: item.detail }))}
        />
        <FeedCard title="Insights" items={report.insights} />
        <FeedCard title="Recommendations" items={report.recommendations} />
      </div>

      <p className="tally">
        <Activity className="icon icon--xs" />
        Recomputed by the scheduled advisor snapshot job.
      </p>
    </div>
  );
}

function FeedCard({
  title,
  items,
}: {
  title: string;
  items: Array<{ key: string; severity: string; domain: string; title: string; text: string }>;
}) {
  return (
    <Card title={title} description={`${items.length} items`}>
      {items.length === 0 ? (
        <p className="state__empty">Nothing here yet.</p>
      ) : (
        <ul className="divided-list">
          {items.map((item, index) => {
            const Icon = SEVERITY_ICON[item.severity] ?? Info;
            return (
              <li key={`${item.key}-${index}`} className="divided-list__item">
                <Icon className="divided-list__icon icon icon--sm" />
                <div className="divided-list__body">
                  <div className="divided-list__head">
                    <p className="divided-list__title">{item.title}</p>
                    <SeverityBadge severity={item.severity} />
                  </div>
                  <p className="divided-list__text">{item.text}</p>
                </div>
              </li>
            );
          })}
        </ul>
      )}
    </Card>
  );
}

function BadgeLike({ children }: { children: ReactNode }) {
  return <span className="badge badge--gray">{children}</span>;
}
